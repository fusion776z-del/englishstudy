// build-eiken-js.mjs
import fs from "fs";
import path from "path";

const pages = [
  { id: "eiken_4-5", src: "eiken_4-5.html", label: "4,5級", hint: "中学英語の土台。ここが固まらないと3級は無理。" },
  { id: "eiken_3", src: "eiken_3.html", label: "3級", hint: "共通テストは4割程度だ。" },
  { id: "eiken_pre2", src: "eiken_pre2.html", label: "準2級", hint: "共通テストは5割程度だ。" },
  { id: "eiken_2", src: "eiken_2.html", label: "2級", hint: "上振れたとしても共通テストは7割程度だ。MARCH一般のスタートライン。" },
  { id: "eiken_pre1", src: "eiken_pre1.html", label: "準1級", hint: "共通テスト8割以上は固い。旧帝、早慶狙うなら最低でもここ。" }
];

fs.mkdirSync("pages", { recursive: true });
const availablePages = [];

for (const page of pages) {
  if (!fs.existsSync(page.src)) {
    console.warn(`SKIP: ${page.src} が見つかりません`);
    continue;
  }
  const html = fs.readFileSync(page.src, "utf8");
  const js = `// Auto-generated from ${page.src}
window.__EIKEN_PAGE__ = {
  id: ${JSON.stringify(page.id)},
  label: ${JSON.stringify(page.label)},
  html: ${JSON.stringify(html)}
};
`;
  fs.writeFileSync(path.join("pages", `${page.id}.js`), js, "utf8");
  availablePages.push({ id: page.id, label: page.label, hint: page.hint, href: `eiken_loader.html?page=${encodeURIComponent(page.id)}` });
  console.log(`CREATED: pages/${page.id}.js`);
}

const indexData = `// Auto-generated by build-eiken-js.mjs
window.EIKEN_PAGES = ${JSON.stringify(availablePages, null, 2)};
`;
fs.writeFileSync("eiken_pages.js", indexData, "utf8");
console.log("CREATED: eiken_pages.js");
console.log("DONE");
